def add_min(hhmm, minutes):
    h_, m_ = map(int, hhmm.split(":"))
    t = (h_ * 60 + m_ + minutes) % (24 * 60)
    return f"{t // 60:02d}:{t % 60:02d}"


def gantt(doc, key):
    sc = SCENARIOS[key]
    devs = list(sc["devs"])
    nslot = max(len(v) for v in sc["devs"].values())
    head = ["회차 시작 기준", *devs, "교통량(영상)", "기상·기록"]
    rows = [head]
    fills = {}
    rows.append(["−0:15 ~ −0:05", *["교정(전)"] * len(devs), "카메라 설치·시각 확인", "기상 1회"])
    for c, d in enumerate(devs, start=1):
        fills[(1, c)] = NOTE_FILL
    for s in range(nslot):
        t0, t1, t2 = s * 20, s * 20 + 10, s * 20 + 20
        r_meas = [f"+{t0 // 60}:{t0 % 60:02d} ~ +{t1 // 60}:{t1 % 60:02d}"]
        r_move = [f"+{t1 // 60}:{t1 % 60:02d} ~ +{t2 // 60}:{t2 % 60:02d}"]
        for d in devs:
            pts = sc["devs"][d]
            p = pts[s] if s < len(pts) else "—"
            fixed = all(x == pts[0] for x in pts)
            r_meas.append(f"**{p}** 측정" if p != "—" else "—")
            r_move.append(f"{p} 연속" if fixed else ("이동·설치" if s < len(pts) - 1 and pts[s + 1] != "—" else "—"))
        r_meas += ["5분 단위 계수", "기상·이상소음"]
        r_move += ["계속 녹화", "신호주기"]
        rows.append(r_meas)
        rows.append(r_move)
        ri = len(rows) - 2
        for c, d in enumerate(devs, start=1):
            pts = sc["devs"][d]
            if s < len(pts) and pts[s] != "—":
                fills[(ri, c)] = DEV_FILL[d]
                if all(x == pts[0] for x in pts):
                    fills[(ri + 1, c)] = DEV_FILL[d]
        fills[(ri, len(devs) + 1)] = DEV_FILL["CAM"]
        fills[(ri + 1, len(devs) + 1)] = DEV_FILL["CAM"]
    end = nslot * 20
    rows.append([f"+{end // 60}:{end % 60:02d} ~ +{(end + 10) // 60}:{(end + 10) % 60:02d}",
                 *["교정(후)"] * len(devs), "녹화 종료·시각 확인", "기상 1회"])
    for c in range(1, len(devs) + 1):
        fills[(len(rows) - 1, c)] = NOTE_FILL
    w_first, w_last2 = 26, 27
    w_dev = (166 - w_first - 2 * w_last2) / len(devs)
    table(doc, rows, [w_first, *[w_dev] * len(devs), w_last2, w_last2], size=8.5, fills=fills,
          align=["c"] * (len(devs) + 3))
    return nslot


